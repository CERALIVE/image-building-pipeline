#!/usr/bin/env bash
#
# systemd-ordering-cycle.test.sh — offline guard for the boot-time systemd
# dependency graph of the SSH-gate + data-migration units.
#
# It defends against TWO distinct classes of regression, both seen on real
# hardware in this effort:
#
#   (A) ORDERING CYCLES (proof-10 UART boot log, 2026-07-15). ssh.socket is
#       Before=sockets.target (early boot, before basic.target). A guard that is
#       Before=ssh.socket while carrying the default After=basic.target closes
#       ssh.socket -> guard -> basic.target -> sockets.target -> ssh.socket, and
#       systemd DELETES ssh.socket's start job (SSH never starts). The same trap
#       hit ceralive-migrate-data.service vs local-fs.target/var-log.mount. Fix:
#       DefaultDependencies=no.
#
#   (B) MISSING SYSINIT ORDERING (proof-11 UART boot log, 2026-07-15). Opting out
#       of default deps to break (A) ALSO dropped the implicit After=sysinit.target.
#       ceralive-ssh-firstboot.service then raced ahead of systemd-sysusers /
#       systemd-tmpfiles / udev and FAILED under `set -euo pipefail`, taking
#       ssh.service/ssh.socket down with "Dependency failed" — with ZERO ordering
#       cycles in the boot log. Fix: re-add After=sysinit.target explicitly (the
#       SAFE half of the default deps; sysinit.target is ordered before
#       sockets.target so it cannot re-close the ssh.socket loop).
#
# A cycle-only test would NOT have caught (B) (proof-11 had zero cycles yet still
# failed), so this test asserts BOTH acyclicity AND real ordering:
#
#   Part A — static contract (systemd-version independent).
#   Part B — dynamic proof via `systemd-analyze verify --root`:
#              B1 the assembled unit set has ZERO ordering cycles, and
#              B2 each Before=ssh.socket guard is TRANSITIVELY ordered after
#                 systemd-sysusers.service and systemd-tmpfiles-setup.service.
#            (B2) is proven with an ordering PROBE: a throwaway unit that is
#            After=<guard> Before=<sysinit-phase unit> MUST close a cycle iff the
#            guard is genuinely ordered after that unit. This turns an ordering
#            question into one `systemd-analyze verify` can answer offline.
#
# shellcheck disable=SC2016

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PIPELINE_DIR="$(cd "${HERE}/.." && pwd)"
RUNTIME="${PIPELINE_DIR}/mkosi/runtime"
POSTINST_ENTRY="${PIPELINE_DIR}/mkosi/customize/postinst-lib.sh"
POSTINST_D="${PIPELINE_DIR}/mkosi/customize/postinst.d"
FIRSTBOOT="${RUNTIME}/ceralive-ssh-firstboot.service"
CIUART="${RUNTIME}/ceralive-ci-uart-bootstrap.service"
MACHINEID="${RUNTIME}/machine-id/ceralive-machine-id.service"
JOURNAL_FLUSH_DROPIN="${RUNTIME}/journald/10-ceralive-journal-flush.conf"
DPKG_RECOVER="${RUNTIME}/ceralive-dpkg-recover.service"

fail() { printf 'systemd-ordering-cycle regression: %s\n' "$1" >&2; exit 1; }

for f in "${FIRSTBOOT}" "${CIUART}" "${MACHINEID}" "${JOURNAL_FLUSH_DROPIN}" "${DPKG_RECOVER}" "${POSTINST_ENTRY}"; do
  [[ -f "${f}" ]] || fail "missing source file: ${f}"
done
[[ -d "${POSTINST_D}" ]] || fail "missing module dir: ${POSTINST_D}"

# postinst-lib.sh is a thin entry that sources the per-concern modules under
# postinst.d/, and the units extracted below are generated by those modules. The
# extraction must read the WHOLE set: pointed at the entry alone it would find
# nothing and every `grep -q ... && fail` below would go quietly vacuous.
#
# Materialized ONCE into a variable, never piped: every extractor below stops
# reading at its heredoc terminator (`awk … { exit }`), which closes the pipe,
# kills `cat` with SIGPIPE, and `set -o pipefail` then reports a correct read as
# a failure. Whether it fires depends on how many unread bytes are left against
# the 64 KiB pipe buffer, so the pipe form passes until a module is added and
# then breaks a test that has nothing to do with the change.
POSTINST_SRC="$(cat "${POSTINST_ENTRY}" "${POSTINST_D}"/*.sh)"

# ---------------------------------------------------------------------------
# Part A — static contract (version independent)
# ---------------------------------------------------------------------------

# Any unit ordered Before=ssh.socket must (A) opt out of default dependencies to
# avoid the ssh.socket cycle, and (B) explicitly re-add After=sysinit.target so it
# still runs after the sysinit phase (users/tmpfiles/udev/RNG) it depends on.
for unit in "${FIRSTBOOT}" "${CIUART}"; do
  base="$(basename "${unit}")"
  grep -Fq 'Before=ssh.service ssh.socket' "${unit}" \
    || fail "${base} no longer orders Before=ssh.service ssh.socket (guard contract changed)"
  grep -Eq '^DefaultDependencies=no$' "${unit}" \
    || fail "${base} is Before=ssh.socket but lacks DefaultDependencies=no — reopens the ssh.socket ordering cycle"
  grep -Eq '^After=.*\bsysinit\.target\b' "${unit}" \
    || fail "${base} has DefaultDependencies=no but no After=sysinit.target — races ahead of sysusers/tmpfiles (proof-11 failure)"
  grep -Eq '^After=.*\bbasic\.target\b' "${unit}" \
    && fail "${base} must NOT be After=basic.target — that re-closes the ssh.socket ordering cycle"
done

# ceralive-migrate-data.service (generated inline by postinst-lib.sh) must run in
# the local-fs setup phase, not after it. It CANNOT be After=sysinit.target
# (sysinit.target is After=local-fs.target — that would cycle); it only touches
# /data + rootfs paths as root, so it needs no sysinit-phase ordering.
mig="$(awk '
  /cat >\/etc\/systemd\/system\/ceralive-migrate-data\.service <<EOF/ { f=1; next }
  f && /^EOF$/ { exit }
  f { print }
' <<<"${POSTINST_SRC}")"
[[ -n "${mig}" ]] || fail "could not extract ceralive-migrate-data.service heredoc from the postinst library"
grep -Eq '^DefaultDependencies=no$' <<<"${mig}" \
  || fail "ceralive-migrate-data.service lacks DefaultDependencies=no — reopens the local-fs.target ordering cycle"
grep -Eq '^After=local-fs\.target$' <<<"${mig}" \
  && fail "ceralive-migrate-data.service still has After=local-fs.target — closes local-fs.target <-> var-log.mount cycle"
grep -Eq '^Before=.*\blocal-fs\.target\b' <<<"${mig}" \
  || fail "ceralive-migrate-data.service must be Before=local-fs.target (run before the bind mounts it seeds)"
grep -Eq '\bsysinit\.target\b' <<<"${mig}" \
  && fail "ceralive-migrate-data.service must NOT reference sysinit.target — it runs in the local-fs phase (would cycle)"

# ceralive-hostname.service (generated inline by postinst-lib.sh) delegates
# no-uplink handling to its allocator. It must order after NetworkManager starts,
# but a network-online.target edge would make ordinary offline boot fail.
hostname_unit="$(awk '
  /cat >\/etc\/systemd\/system\/ceralive-hostname\.service <<'\''EOF'\''/ { f=1; next }
  f && /^EOF$/ { exit }
  f { print }
' <<<"${POSTINST_SRC}")"
[[ -n "${hostname_unit}" ]] || fail "could not extract ceralive-hostname.service heredoc from the postinst library"
grep -Eq '^After=.*\bNetworkManager\.service\b' <<<"${hostname_unit}" \
  || fail "ceralive-hostname.service lacks After=NetworkManager.service"
grep -Eq '^Wants=.*\bNetworkManager\.service\b' <<<"${hostname_unit}" \
  || fail "ceralive-hostname.service lacks Wants=NetworkManager.service"
grep -Eq '\bnetwork-online\.target\b' <<<"${hostname_unit}" \
  && fail "ceralive-hostname.service must not depend on network-online.target"

# The stock flush unit already RequiresMountsFor=/var/log/journal, but the
# machine-id unit can restart journald after committing the persistent id. The
# two early-boot jobs must be serialized so journalctl --flush cannot race that
# restart. A hard requirement keeps the ordering true even if enablement moves.
grep -Eq '^Requires=.*\bceralive-machine-id\.service\b' "${JOURNAL_FLUSH_DROPIN}" \
  || fail "systemd-journal-flush.service does not require machine-id reconciliation"
grep -Eq '^After=.*\bceralive-machine-id\.service\b' "${JOURNAL_FLUSH_DROPIN}" \
  || fail "systemd-journal-flush.service can race the machine-id-triggered journald restart"
grep -Eq '^RequiresMountsFor=.*\B/var/log/journal\b' "${JOURNAL_FLUSH_DROPIN}" \
  || fail "systemd-journal-flush.service does not explicitly retain the persistent /var/log mount guard"

grep -Fxq 'After=local-fs.target' "${DPKG_RECOVER}" || fail 'dpkg recovery must follow local filesystems'
grep -Fxq 'Before=ceralive.service ceralive-healthcheck.service' "${DPKG_RECOVER}" || fail 'dpkg recovery must precede app and health confirmation'
grep -Fq 'setup_dpkg_recovery' "${POSTINST_D}/services.sh" || fail 'dpkg recovery installer is not wired into configure_services'

echo "systemd-ordering-cycle: Part A static contract OK"

# ---------------------------------------------------------------------------
# Part B — dynamic proof via systemd-analyze verify
# ---------------------------------------------------------------------------
if ! command -v systemd-analyze >/dev/null 2>&1 || ! command -v systemctl >/dev/null 2>&1; then
  echo "systemd-ordering-cycle: systemd-analyze/systemctl unavailable — skipping dynamic proof (static contract enforced)"
  echo "systemd-ordering-cycle regression: PASS (static only)"
  exit 0
fi

SYS_LIB=""
for cand in /usr/lib/systemd/system /lib/systemd/system; do
  [[ -d "${cand}" ]] && { SYS_LIB="${cand}"; break; }
done
[[ -n "${SYS_LIB}" ]] || { echo "systemd-ordering-cycle: no host systemd unit tree — skipping dynamic proof"; exit 0; }

TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT
S="${TMP}/root"
ETC="${S}/etc/systemd/system"
mkdir -p "${ETC}" "${S}/usr/lib/systemd/system" "${S}/etc/ssh" "${S}/usr/local/sbin"
cp -a "${SYS_LIB}/." "${S}/usr/lib/systemd/system/" 2>/dev/null || true
for exe in ceralive-ssh-firstboot ceralive-ci-uart-bootstrap ceralive-migrate-data ceralive-machine-id; do
  printf '#!/bin/sh\nexit 0\n' >"${S}/usr/local/sbin/${exe}"; chmod 0755 "${S}/usr/local/sbin/${exe}"
done

# faithful Debian ssh.socket/ssh.service (Before=sockets.target, no Conflicts)
cat >"${S}/usr/lib/systemd/system/ssh.socket" <<'EOF'
[Unit]
Description=OpenBSD Secure Shell server socket
Before=sockets.target
[Socket]
ListenStream=22
Accept=no
[Install]
WantedBy=sockets.target
EOF
cat >"${S}/usr/lib/systemd/system/ssh.service" <<'EOF'
[Unit]
Description=OpenBSD Secure Shell server
After=network.target
[Service]
ExecStart=/usr/sbin/sshd -D
Type=simple
[Install]
WantedBy=multi-user.target
EOF

# real device units under test
cp "${FIRSTBOOT}" "${ETC}/ceralive-ssh-firstboot.service"
cp "${CIUART}"    "${ETC}/ceralive-ci-uart-bootstrap.service"

# render the generated migrate-data + bind-mount units straight from postinst-lib.sh
printf '%s\n' "${mig}" | sed 's#${data_root}#/data#g' >"${ETC}/ceralive-migrate-data.service"
mount_tpl="$(awk '
  /cat >"\/etc\/systemd\/system\/\$\{unit\}" <<EOF/ { f=1; next }
  f && /^EOF$/ { exit }
  f { print }
' <<<"${POSTINST_SRC}")"
[[ -n "${mount_tpl}" ]] || fail "could not extract bind-mount heredoc from the postinst library"
render_mount() { # $1=src $2=dst $3=unitname
  printf '%s\n' "${mount_tpl}" \
    | sed -e "s#\${data_root}#/data#g" -e "s#\${src}#$1#g" -e "s#\${dst}#$2#g" \
    >"${ETC}/$3"
}
render_mount /data/log       /var/log       var-log.mount
render_mount /data/ceralive  /opt/ceralive  opt-ceralive.mount
nm_bind=$(systemd-escape -p --suffix=mount /etc/NetworkManager/system-connections)
render_mount /data/nm/system-connections /etc/NetworkManager/system-connections "$nm_bind"

# Execute the shipped ROCK persistence installer through its early-unit block.
# Rewrite only output paths outside heredocs; unit bodies and fstab options are
# rendered by the actual shell code, not duplicate fixtures. Later migration /
# bind mounts are rendered below as before. No host filesystem is modified.
python3 - "${POSTINST_D}/persistence.sh" "${TMP}/render-growth.sh" <<'PY_RENDER'
from pathlib import Path
import re, sys
text=Path(sys.argv[1]).read_text().split('setup_data_persistence() {',1)[1]
text, boundary, _=text.partition('\n  mkdir -p /usr/local/sbin')
assert boundary, 'persistence installer boundary missing'
lines=[]
heredoc=None
for line in text.splitlines():
    if heredoc:
        lines.append(line)
        if line == heredoc:
            heredoc=None
        continue
    match=re.search(r"<<['\"]?(\w+)",line)
    line=line.replace('/etc/', '${S}/etc/').replace('/usr/', '${S}/usr/')
    line=line.replace('mkdir -p "${data_root}"', 'mkdir -p "${S}${data_root}"')
    line=line.replace('install_bounded_apt_metadata /', 'install_bounded_apt_metadata "${S}"')
    lines.append(line)
    if match:
        heredoc=match[1]
Path(sys.argv[2]).write_text('setup_data_persistence() {\n'+'\n'.join(lines)+'\n}\nsetup_data_persistence\n')
PY_RENDER
# Load the real helper definitions, then render their call into the private tree.
# shellcheck source=mkosi/customize/postinst.d/persistence.sh
source "${POSTINST_D}/persistence.sh"
export S CERALIVE_RUNTIME_SRC="${RUNTIME}" BOARD_ID=rock-5b-plus
log() { :; }
resolve_partlabel() { printf '%s\n' data; }
# shellcheck source=/dev/null
source "${TMP}/render-growth.sh"

# Feed the rendered fstab through the real host generator, including growfs,
# fsck, nofail, and the partition-growth ordering edge. Keep the real stock
# growfs template copied with the systemd tree above.
FSTAB_GENERATOR="${SYS_LIB%/system}/system-generators/systemd-fstab-generator"
[[ -x "${FSTAB_GENERATOR}" ]] || fail 'systemd fstab generator unavailable'
SYSTEMD_FSTAB="${S}/etc/fstab" SYSTEMD_IN_INITRD=no \
  "${FSTAB_GENERATOR}" "${ETC}" "${ETC}" "${ETC}" >"${TMP}/fstab-generator.log" 2>&1 \
  || { cat "${TMP}/fstab-generator.log" >&2; fail 'fstab generation failed'; }
[[ -s "${ETC}/data.mount" ]] || fail 'fstab generator did not emit data.mount'
[[ -e "${ETC}/data.mount.wants/systemd-growfs@data.service" ]] \
  || fail 'fstab no longer pulls filesystem growth in'
# Package-owned service payloads are stubs; their installed readiness drop-ins
# are real and must participate in the same transaction as app and health.
for consumer in rauc rauc-hawkbit-updater; do
  printf '[Service]\nExecStart=/bin/true\n' >"${ETC}/${consumer}.service"
done

cat >"${ETC}/ceralive.service" <<'EOF'
[Unit]
Description=ceralive.service stub
[Service]
ExecStart=/bin/true
[Install]
WantedBy=multi-user.target
EOF
cat >"${ETC}/NetworkManager.service" <<'EOF'
[Unit]
Description=NetworkManager stub
[Service]
ExecStart=/bin/true
[Install]
WantedBy=multi-user.target
EOF

# Render the REAL ceralive-hostname.service (not a stub) so B1 acyclicity also
# proves the network-online.target addition introduced no cycle, and Part C can
# probe its ordering. Its ExecStart target is stubbed above in /usr/local/sbin.
printf '#!/bin/sh\nexit 0\n' >"${S}/usr/local/sbin/ceralive-set-hostname"
chmod 0755 "${S}/usr/local/sbin/ceralive-set-hostname"
printf '%s\n' "${hostname_unit}" >"${ETC}/ceralive-hostname.service"

# The persistent machine-id unit is the newest member of the local-fs phase, and
# it is the one whose ordering is load-bearing rather than incidental: it must
# land after the /var/log bind (so a journald restart reopens the journal on
# /data, not on the rootfs slot) and before every consumer that reads the id.
# Part D probes both edges; enabling it here also puts it inside B1's acyclicity
# proof, which is what a Before=local-fs.target unit most needs.
cp "${MACHINEID}" "${ETC}/ceralive-machine-id.service"
cp "${DPKG_RECOVER}" "${ETC}/ceralive-dpkg-recover.service"
install -D -m 0755 "${RUNTIME}/ceralive-dpkg-recover.sh" "${S}/usr/libexec/ceralive/ceralive-dpkg-recover"
cp "${RUNTIME}/ceralive-healthcheck.service" "${ETC}/ceralive-healthcheck.service"
install -D -m 0755 "${RUNTIME}/ceralive-healthcheck.sh" "${S}/usr/local/bin/ceralive-healthcheck.sh"
mkdir -p "${ETC}/systemd-journal-flush.service.d"
cp "${JOURNAL_FLUSH_DROPIN}" "${ETC}/systemd-journal-flush.service.d/10-ceralive-persistence.conf"

systemctl --root "${S}" enable \
  ssh.socket ceralive-ssh-firstboot.service ceralive-ci-uart-bootstrap.service \
  ceralive-migrate-data.service var-log.mount opt-ceralive.mount data.mount \
  "$nm_bind" ceralive.service NetworkManager.service ceralive-hostname.service \
  ceralive-machine-id.service ceralive-dpkg-recover.service ceralive-healthcheck.service >/dev/null 2>&1 || true
mkdir -p "${ETC}/multi-user.target.wants"
ln -sf ../ssh.service "${ETC}/multi-user.target.wants/ssh.service"
for consumer in rauc rauc-hawkbit-updater; do
  ln -sf "../${consumer}.service" "${ETC}/multi-user.target.wants/${consumer}.service"
done
ln -sf "${SYS_LIB}/multi-user.target" "${ETC}/default.target"

# systemd-analyze verify is non-deterministic in WHICH job it deletes to break a
# cycle, so count matched cycle lines across a few runs.
count_cycles() {
  local out n total=0 target="${1:-default.target}"
  for _ in 1 2 3; do
    out="$(systemd-analyze verify --root "${S}" "${target}" 2>&1 || true)"
    n="$(printf '%s\n' "${out}" | grep -c 'Found ordering cycle' || true)"
    total=$((total + n))
  done
  printf '%s' "${total}"
}

# --- B1: the assembled unit set must be acyclic ---------------------------------
base_cycles="$(count_cycles)"
if (( base_cycles > 0 )); then
  systemd-analyze verify --root "${S}" default.target 2>&1 \
    | grep -E 'Found ordering cycle|deleted to break' | sort -u >&2
  fail "assembled unit set has ${base_cycles} ordering cycle(s) — see above"
fi
echo "systemd-ordering-cycle: Part B1 acyclic OK (systemd $(systemd-analyze --version | awk 'NR==1{print $2}'))"

# --- B2: prove each guard is transitively After the sysinit-phase units ---------
# Inject a probe unit After=<guard> Before=<sysinit unit>. If (and only if) the
# guard is genuinely ordered after that sysinit unit, the probe closes a cycle.
probe_orders_after() { # $1=guard unit  $2=target sysinit unit -> 0 if guard is After target
  local guard="$1" target="$2" probe="${ETC}/zz-order-probe.service"
  cat >"${probe}" <<EOF
[Unit]
Description=ordering probe (${guard} after ${target})
DefaultDependencies=no
After=${guard}
Before=${target}
[Service]
Type=oneshot
ExecStart=/bin/true
[Install]
WantedBy=sysinit.target
EOF
  mkdir -p "${ETC}/sysinit.target.wants"
  ln -sf ../zz-order-probe.service "${ETC}/sysinit.target.wants/zz-order-probe.service"
  local c; c="$(count_cycles)"
  rm -f "${probe}" "${ETC}/sysinit.target.wants/zz-order-probe.service"
  (( c > 0 ))
}

checked=0
for target in systemd-sysusers.service systemd-tmpfiles-setup.service; do
  [[ -f "${SYS_LIB}/${target}" ]] || { echo "systemd-ordering-cycle: ${target} absent — skipping its ordering probe"; continue; }
  for guard in ceralive-ssh-firstboot.service ceralive-ci-uart-bootstrap.service; do
    probe_orders_after "${guard}" "${target}" \
      || fail "${guard} is NOT ordered after ${target} (missing After=sysinit.target — proof-11 runtime failure)"
    checked=$((checked + 1))
  done
done

# Backstop when neither sysinit unit shipped: prove After=sysinit.target directly.
if (( checked == 0 )); then
  for guard in ceralive-ssh-firstboot.service ceralive-ci-uart-bootstrap.service; do
    probe_orders_after "${guard}" sysinit.target \
      || fail "${guard} is NOT ordered after sysinit.target (proof-11 runtime failure)"
  done
fi

echo "systemd-ordering-cycle: Part B2 sysinit ordering OK (guards run after sysusers/tmpfiles)"

# --- Part C: prove ceralive-hostname.service is ordered After NetworkManager.service ---
# Same probe technique as B2: a unit After=ceralive-hostname.service
# Before=NetworkManager.service closes a cycle iff the hostname unit is genuinely
# ordered after NetworkManager.service. This is the dynamic proof of the boot contract
# (the static After=/Wants= assertion is in Part A).
probe_orders_after ceralive-hostname.service NetworkManager.service \
  || fail "ceralive-hostname.service is NOT ordered after NetworkManager.service"
echo "systemd-ordering-cycle: Part C NetworkManager ordering OK (hostname starts without an uplink gate)"

# --- Part D: prove the machine-id unit is supplied EARLY ENOUGH -------------------
# Same probe technique as B2/C. Two edges, each of which is a real defect if it
# is missing:
#   * after var-log.mount — journald caches the machine-id at startup, so the
#     restart this unit issues must happen once /var/log is the /data bind, or
#     the reopened journal lands in the rootfs slot and is lost on the next OTA.
#   * before ceralive-hostname.service — that unit DIES on a machine-id that is
#     not a committed 32-hex value (postinst.d/hostname.sh), and it is the first
#     consumer to read it.
probe_orders_after ceralive-machine-id.service var-log.mount \
  || fail "ceralive-machine-id.service is NOT ordered after var-log.mount — a journald restart would reopen the journal on the rootfs slot"
probe_orders_after ceralive-hostname.service ceralive-machine-id.service \
  || fail "ceralive-hostname.service is NOT ordered after ceralive-machine-id.service — it would read whatever id PID 1 invented"
probe_orders_after systemd-journal-flush.service ceralive-machine-id.service \
  || fail "systemd-journal-flush.service is NOT ordered after ceralive-machine-id.service — journalctl --flush can race its journald restart"
probe_orders_after systemd-journal-flush.service var-log.mount \
  || fail "systemd-journal-flush.service is NOT ordered after var-log.mount — persistent flush can target the rootfs slot"
echo "systemd-ordering-cycle: Part D persistence ordering OK (mount, machine-id reconciliation, journal flush, consumers)"

probe_orders_after ceralive-dpkg-recover.service local-fs.target \
  || fail 'dpkg recovery is not ordered after local-fs.target'
probe_orders_after ceralive.service ceralive-dpkg-recover.service \
  || fail 'ceralive.service can start before dpkg recovery'
probe_orders_after ceralive-healthcheck.service ceralive-dpkg-recover.service \
  || fail 'healthcheck can start before dpkg recovery'
echo 'systemd-ordering-cycle: Part E dpkg recovery ordering OK (filesystem, recovery, app, confirmation)'

# --- Part F: ROCK growth -> mount -> growfs -> readiness -> consumers ----
for edge in \
  'data.mount ceralive-grow-data.service' \
  'systemd-growfs@data.service data.mount' \
  'ceralive-migrate-data.service systemd-growfs@data.service' \
  'var-log.mount systemd-growfs@data.service' \
  'opt-ceralive.mount systemd-growfs@data.service' \
  "$nm_bind systemd-growfs@data.service" \
  'ceralive-data-ready.service systemd-growfs@data.service' \
  'ceralive-data-ready.service ceralive-grow-data.service'; do
  read -r later earlier <<<"$edge"
  probe_orders_after "$later" "$earlier" || fail "$later can precede $earlier"
done
# Requires alone can still start repair in parallel; prove the ordering too.
data_fsck=$(systemd-escape --path --template=systemd-fsck@.service /dev/disk/by-partlabel/data)
probe_orders_after "$data_fsck" ceralive-grow-data.service || fail 'fsck can start before growth finishes'
for consumer in ceralive ceralive-healthcheck rauc rauc-hawkbit-updater; do
  probe_orders_after "${consumer}.service" ceralive-data-ready.service \
    || fail "${consumer} can precede data readiness"
done
# SSH must retain data-mount/identity ordering but not wait for app/update
# readiness. Rescue must remain acyclic and independent of readiness too.
for ssh in ssh.service ssh.socket; do
  probe_orders_after "$ssh" data.mount || fail "$ssh can precede persistent identity mount"
  if probe_orders_after "$ssh" ceralive-data-ready.service; then
    fail "$ssh waits for readiness, obstructing diagnostics"
  fi
done
(( $(count_cycles rescue.target) == 0 )) || fail 'rescue transaction has an ordering cycle'
if probe_orders_after rescue.target ceralive-data-ready.service; then
  fail 'rescue waits for application data readiness'
fi
# Check hard dependency reachability as well as ordering: a bare Requires=
# could make readiness failure stop SSH without adding any ordering cycle.
check_rescue_dependencies() {
  python3 - "$ETC" "${S}/usr/lib/systemd/system" <<'PY_DEPS'
import configparser
from pathlib import Path
import sys
roots=[Path(p) for p in sys.argv[1:]]
readiness=configparser.ConfigParser(interpolation=None)
readiness.read(roots[0]/'ceralive-data-ready.service')
assert readiness.get('Service','Type') == 'oneshot'
assert readiness.get('Service','TimeoutStartSec') == '30s'
assert readiness.get('Service','Restart') == 'no'
def dependencies(unit):
    names=[unit]
    if '@' in unit:
        names.append(unit.split('@',1)[0]+'@.service')
    body=next((r/n for n in names for r in roots if (r/n).is_file()),None)
